-- тюнинг под нагрузку: инвариант "у врача один приём на момент времени" переносится в БД.
-- Прежняя проверка в коде была (а) глобальной — два разных врача не могли принимать
-- в одну и ту же секунду, (б) check-then-act селектом — под конкурентной нагрузкой
-- всё равно не гарантировала уникальность. Уникальный индекс решает обе проблемы,
-- а заодно обслуживает горячую выборку "приёмы врача, отсортированные по дате".
CREATE UNIQUE INDEX uq_appointments_doctor_slot ON appointments (doctor, appointment_date);

-- тюнинг под нагрузку: (doctor) — префикс нового составного индекса, отдельный дубль
-- только замедляет вставку (8.9% трафика — запись)
DROP INDEX idx_appointments_doctor;

-- тюнинг под нагрузку: глобальной проверки слота по одной лишь дате больше нет —
-- индекс по appointment_date не обслуживает ни один оставшийся запрос
DROP INDEX idx_appointments_date;
